package com.microboxlabs.miot.teltonika.mapping;

import static com.microboxlabs.miot.teltonika.mapping.TeltonikaIo.*;

import cl.streamhub.gps.model.Acceleration;
import cl.streamhub.gps.model.AdditionalInfo;
import cl.streamhub.gps.model.AssetTrackingData;
import cl.streamhub.gps.model.DriverInfo;
import cl.streamhub.gps.model.Event;
import cl.streamhub.gps.model.Gps;
import cl.streamhub.gps.model.Odometer;
import cl.streamhub.gps.model.Sensors;
import cl.streamhub.gps.model.Telecom;
import cl.streamhub.gps.model.metrics.MetricItem;
import cl.streamhub.gps.model.metrics.MetricQuality;
import cl.streamhub.gps.model.metrics.MetricSource;
import cl.streamhub.gps.model.metrics.MetricsEnvelope;
import com.microboxlabs.miot.teltonika.protocol.AvlRecord;
import com.microboxlabs.miot.teltonika.protocol.IoElement;
import java.time.ZoneOffset;
import java.time.ZonedDateTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Translates one Teltonika AVL record into the {@code AssetTrackingData} accepted by
 * {@code /v1/asset/track}. Mapping table: requerimiento_fmb920.md, section 5, and the module README.
 *
 * <p>Values without a field of their own travel in one extension metric, {@value #IO_METRIC}, whose
 * value is an object by name (tracking keeps one extension metric per asset and instant, so several
 * extension items at the same time would collapse into one).
 */
public final class AvlRecordMapper {

    public static final String METRICS_SCHEMA = "miot.metrics@1.0";
    public static final String IO_METRIC = "x.teltonika.io";

    /** Dallas temperature sensors: signed, tenths of a degree Celsius. */
    private static final Map<Integer, String> DALLAS_TEMPERATURES = Map.of(
            72, "dallas_temp_1_c", 73, "dallas_temp_2_c", 74, "dallas_temp_3_c", 75, "dallas_temp_4_c");
    /** Crash detection value for a real crash on a calibrated device; other values are partial traces. */
    private static final int REAL_CRASH = 1;

    /** IDs mapped to a model field, an event or a named value; not repeated as {@code io_<id>}. */
    private static final Set<Integer> NAMED = Set.of(
            IGNITION, TOTAL_ODOMETER, TRIP_ODOMETER, AXIS_X, AXIS_Y, AXIS_Z, IBUTTON,
            GSM_CELL_ID, GSM_AREA_CODE, ACTIVE_GSM_OPERATOR, EXTERNAL_VOLTAGE,
            GSM_SIGNAL, BATTERY_VOLTAGE, ANALOG_INPUT_1, ANALOG_INPUT_2, DIGITAL_INPUT_1, DIGITAL_INPUT_2, DIGITAL_INPUT_3, DIGITAL_INPUT_4,
            MOVEMENT, GNSS_STATUS, GNSS_HDOP, GNSS_PDOP, SLEEP_MODE, DATA_MODE,
            GREEN_DRIVING_TYPE, GREEN_DRIVING_VALUE, OVER_SPEEDING, CRASH_DETECTION, UNPLUG,
            JAMMING, TOWING, 72, 73, 74, 75);

    private final String gpsProvider;
    private final boolean lastKnownPosition;

    public AvlRecordMapper(String gpsProvider) {
        this(gpsProvider, true);
    }

    /**
     * @param lastKnownPosition keep the position of a record without a current fix (FMB devices
     *                          repeat the last known one); when false, such records carry no gps
     */
    public AvlRecordMapper(String gpsProvider, boolean lastKnownPosition) {
        this.gpsProvider = gpsProvider;
        this.lastKnownPosition = lastKnownPosition;
    }

    public AssetTrackingData map(AvlRecord avl, String assetId) {
        return map(avl, assetId, true);
    }

    /**
     * @param speedingStart for a record generated by over speeding (ID 255): whether it is the start
     *                      of the episode; the end record carries no event
     */
    public AssetTrackingData map(AvlRecord avl, String assetId, boolean speedingStart) {
        ZonedDateTime time = avl.timestamp().atZone(ZoneOffset.UTC);
        var data = new AssetTrackingData();
        data.setAssetId(assetId);
        data.setTimestamp(time);
        data.setGps(gps(avl));
        data.setTelecom(telecom(avl));
        data.setSensors(sensors(avl));
        data.setDriverInfo(driverInfo(avl));
        List<Event> events = events(avl, time, speedingStart);
        if (!events.isEmpty()) {
            data.setEvents(events);
        }
        data.setMetrics(metrics(avl, time));
        return data;
    }

    /** False when the record carries no position at all (0/0). */
    public static boolean hasPosition(AvlRecord avl) {
        return validPosition(avl.latitude(), avl.longitude());
    }

    /** A real position: finite, inside ±90 / ±180, and not the 0/0 a device reports without one. */
    public static boolean validPosition(double latitude, double longitude) {
        return Double.isFinite(latitude) && Double.isFinite(longitude) && Math.abs(latitude) <= 90
                && Math.abs(longitude) <= 180 && (latitude != 0 || longitude != 0);
    }

    /** True when the device reports a current fix (GNSS status 1, or satellites when the status is absent). */
    public static boolean hasCurrentFix(AvlRecord avl) {
        IoElement status = avl.ioElement(GNSS_STATUS);
        return status != null ? status.unsigned() == 1 : avl.satellites() > 0;
    }

    private Gps gps(AvlRecord avl) {
        if (!hasPosition(avl) || (!lastKnownPosition && !hasCurrentFix(avl))) {
            return null;
        }
        var gps = new Gps();
        gps.setLatitude(avl.latitude());
        gps.setLongitude(avl.longitude());
        gps.setAltitude(avl.altitude());
        gps.setHeading(avl.angle());
        gps.setSpeed(avl.speed());
        gps.setSatellites(avl.satellites());
        return gps;
    }

    /** {@code signal_strength} is dBm in the model; the device's 0-5 scale goes to the IO metric. */
    private Telecom telecom(AvlRecord avl) {
        var telecom = new Telecom();
        telecom.setGpsProvider(gpsProvider);
        IoElement cell = avl.ioElement(GSM_CELL_ID);
        if (cell != null) {
            telecom.setCellId(cell.unsignedText());
        }
        IoElement area = avl.ioElement(GSM_AREA_CODE);
        if (area != null) {
            telecom.setLac(area.unsignedText());
        }
        IoElement operator = avl.ioElement(ACTIVE_GSM_OPERATOR);
        if (operator != null && !operator.isZero()) {
            String code = operator.unsignedText();
            telecom.setOperator(code);
            if (code.length() > 3) {
                telecom.setMcc(code.substring(0, 3));
                telecom.setMnc(code.substring(3));
            }
        }
        return telecom;
    }

    private static Sensors sensors(AvlRecord avl) {
        var sensors = new Sensors();
        boolean any = false;
        IoElement ignition = avl.ioElement(IGNITION);
        if (ignition != null) {
            sensors.setEngineStatus(ignition.unsigned() == 1);
            any = true;
        }
        IoElement total = avl.ioElement(TOTAL_ODOMETER);
        IoElement trip = avl.ioElement(TRIP_ODOMETER);
        if (total != null || trip != null) {
            var odometer = new Odometer();
            if (total != null) {
                odometer.setTotalDistance(total.unsigned() / 1000d);
            }
            if (trip != null) {
                odometer.setTripDistance(trip.unsigned() / 1000d);
            }
            sensors.setOdometer(odometer);
            any = true;
        }
        IoElement x = avl.ioElement(AXIS_X);
        IoElement y = avl.ioElement(AXIS_Y);
        IoElement z = avl.ioElement(AXIS_Z);
        if (x != null || y != null || z != null) {
            var acceleration = new Acceleration();
            acceleration.setxAxis(milliGToG(x));
            acceleration.setyAxis(milliGToG(y));
            acceleration.setzAxis(milliGToG(z));
            sensors.setAcceleration(acceleration);
            any = true;
        }
        return any ? sensors : null;
    }

    /** iButton ID as 16 uppercase hex digits, the format already stored for other providers. */
    private static DriverInfo driverInfo(AvlRecord avl) {
        IoElement ibutton = avl.ioElement(IBUTTON);
        if (ibutton == null || ibutton.isZero()) {
            return null;
        }
        var driver = new DriverInfo();
        driver.setIdButton(ibutton.hex());
        return driver;
    }

    /** Only records generated by the event carry it; periodic records repeat the last value. */
    private static List<Event> events(AvlRecord avl, ZonedDateTime time, boolean speedingStart) {
        List<Event> events = new ArrayList<>();
        int trigger = avl.eventIoId();
        IoElement value = trigger == 0 ? null : avl.ioElement(trigger);
        if (value == null) {
            return events;
        }
        switch (trigger) {
            case GREEN_DRIVING_TYPE -> greenDriving(avl, value, time, events);
            case OVER_SPEEDING -> {
                if (speedingStart) {
                    var info = new AdditionalInfo();
                    info.setSpeedAtEvent((double) value.unsigned());
                    events.add(event("speeding", time, true, info, null));
                }
            }
            case CRASH_DETECTION -> {
                if (value.unsigned() == REAL_CRASH) {
                    events.add(event("impact", time, true, null, "Teltonika crash detection: real crash"));
                }
            }
            case UNPLUG -> {
                if (value.unsigned() == 1) {
                    events.add(event("power_unplugged", time, null, null, null));
                }
            }
            case JAMMING -> {
                if (value.unsigned() == 1) {
                    events.add(event("gps_jamming", time, null, null, null));
                }
            }
            case TOWING -> {
                if (value.unsigned() == 1) {
                    events.add(event("towing", time, null, null, null));
                }
            }
            default -> {
                // Other triggers (ignition, inputs, periodic) are plain records.
            }
        }
        return events;
    }

    private static void greenDriving(AvlRecord avl, IoElement type, ZonedDateTime time, List<Event> events) {
        IoElement magnitude = avl.ioElement(GREEN_DRIVING_VALUE);
        Double scaled = magnitude == null ? null : magnitude.unsigned() / 100d;
        switch ((int) type.unsigned()) {
            case 1 -> events.add(event("hard_accel", time, true, gForce(scaled), null));
            case 2 -> events.add(event("hard_brake", time, true, gForce(scaled), null));
            case 3 -> events.add(event("hard_turn", time, true, null,
                    scaled == null ? null : "Teltonika cornering value " + scaled));
            default -> {
                // Unknown green driving type: the raw value stays in the IO metric.
            }
        }
    }

    private static AdditionalInfo gForce(Double g) {
        if (g == null) {
            return null;
        }
        var info = new AdditionalInfo();
        info.setgForce(g);
        return info;
    }

    private static Event event(String type, ZonedDateTime time, Boolean thresholdExceeded,
            AdditionalInfo info, String description) {
        var event = new Event();
        event.setEventType(type);
        event.setTimestamp(time);
        if (thresholdExceeded != null) {
            event.setThresholdExceeded(thresholdExceeded);
        }
        event.setAdditionalInfo(info);
        event.setDescription(description);
        return event;
    }

    private static MetricsEnvelope metrics(AvlRecord avl, ZonedDateTime time) {
        List<MetricItem> items = new ArrayList<>();
        IoElement external = avl.ioElement(EXTERNAL_VOLTAGE);
        if (external != null) {
            items.add(item("battery.voltage", external.unsigned() / 1000d, "V", time));
        }
        IoElement total = avl.ioElement(TOTAL_ODOMETER);
        if (total != null) {
            items.add(item("vehicle.odometer", total.unsigned() / 1000d, "km", time));
        }
        items.add(item(IO_METRIC, ioValues(avl), null, time));
        var envelope = new MetricsEnvelope();
        envelope.setSchema(METRICS_SCHEMA);
        envelope.setDeviceTs(time);
        envelope.setItems(items);
        return envelope;
    }

    /** Every value without a field of its own, by name; IDs without a name as {@code io_<id>}. */
    static Map<String, Object> ioValues(AvlRecord avl) {
        Map<String, Object> io = new LinkedHashMap<>();
        io.put("priority", avl.priority());
        if (avl.eventIoId() != 0) {
            io.put("event_io_id", avl.eventIoId());
        }
        flag(io, avl, MOVEMENT, "movement");
        flag(io, avl, DIGITAL_INPUT_1, "din1");
        flag(io, avl, DIGITAL_INPUT_2, "din2");
        flag(io, avl, DIGITAL_INPUT_3, "din3");
        flag(io, avl, DIGITAL_INPUT_4, "din4");
        scaled(io, avl, ANALOG_INPUT_1, "ain1_v", 1000);
        scaled(io, avl, ANALOG_INPUT_2, "ain2_v", 1000);
        scaled(io, avl, BATTERY_VOLTAGE, "battery_voltage_v", 1000);
        scaled(io, avl, GSM_SIGNAL, "gsm_signal", 1);
        scaled(io, avl, GNSS_HDOP, "hdop", 10);
        scaled(io, avl, GNSS_PDOP, "pdop", 10);
        scaled(io, avl, GNSS_STATUS, "gnss_status", 1);
        scaled(io, avl, SLEEP_MODE, "sleep_mode", 1);
        scaled(io, avl, DATA_MODE, "data_mode", 1);
        scaled(io, avl, GREEN_DRIVING_TYPE, "green_driving_type", 1);
        scaled(io, avl, GREEN_DRIVING_VALUE, "green_driving_value", 1);
        scaled(io, avl, OVER_SPEEDING, "over_speeding_kmh", 1);
        scaled(io, avl, CRASH_DETECTION, "crash_detection", 1);
        flag(io, avl, UNPLUG, "unplug");
        flag(io, avl, JAMMING, "jamming");
        flag(io, avl, TOWING, "towing");
        DALLAS_TEMPERATURES.forEach((id, name) -> {
            IoElement t = avl.ioElement(id);
            if (t != null) {
                io.put(name, t.signed() / 10d);
            }
        });
        for (IoElement e : avl.io().values()) {
            if (!NAMED.contains(e.id())) {
                io.put("io_" + e.id(), raw(e));
            }
        }
        return io;
    }

    private static Object raw(IoElement e) {
        return switch (e.length()) {
            case 1, 2, 4 -> e.unsigned();
            case 8 -> e.unsignedText();
            default -> e.hex();
        };
    }

    private static void flag(Map<String, Object> io, AvlRecord avl, int id, String name) {
        IoElement e = avl.ioElement(id);
        if (e != null) {
            io.put(name, e.unsigned() == 1);
        }
    }

    private static void scaled(Map<String, Object> io, AvlRecord avl, int id, String name, int divisor) {
        IoElement e = avl.ioElement(id);
        if (e != null) {
            io.put(name, divisor == 1 ? (Object) e.unsigned() : e.unsigned() / (double) divisor);
        }
    }

    /** Tracking persists metrics with each item's own ts; it is required there. */
    private static MetricItem item(String key, Object value, String unit, ZonedDateTime time) {
        var item = new MetricItem();
        item.setK(key);
        item.setV(value);
        item.setU(unit);
        item.setTs(time);
        item.setSrc(MetricSource.OEM);
        item.setQ(MetricQuality.OK);
        return item;
    }

    private static Double milliGToG(IoElement io) {
        return io == null ? null : io.signed() / 1000d;
    }
}
