package com.microboxlabs.miot.teltonika.inputs;

import cl.streamhub.gps.model.Event;
import java.time.Instant;
import java.time.ZonedDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Turns the inputs a record reports into what the organization wired to them: a named state per
 * input ("Puerta trasera": open) and an event when the state changes ({@code door_open},
 * {@code panic_button}...). The same for every brand: inputs arrive with canonical names.
 *
 * <p>Changes are detected per device against the last state seen, in the order records are
 * published. The first state seen after a restart produces no event (it is not known whether it
 * changed), except when the device says the record was generated by that input.
 * Records older than the last one seen do not move the state (buffered data after an outage).
 * The state moves only when the records are published ({@link Batch}).
 */
public final class InputInterpreter {

    /** Result for one record: named states and events. */
    public record Result(Map<String, Object> states, List<Event> events) {

        public static final Result NONE = new Result(Map.of(), List.of());
    }

    private record Seen(boolean on, Instant at) {
    }

    private final Map<String, Map<String, Seen>> state = new ConcurrentHashMap<>();

    /**
     * The changes of one batch of records: applied to the state only with {@link #commit}, after the
     * batch is published. A batch that fails leaves the state as it was, so the records sent again
     * produce the same events (a door that opened is not lost because the first send failed).
     */
    public static final class Batch {

        private final Map<String, Map<String, Seen>> draft = new HashMap<>();
    }

    public Batch batch() {
        return new Batch();
    }

    /** Applies and commits at once (one record, nothing to wait for). */
    public Result apply(String deviceId, List<InputMapping> mappings, InputReading reading, ZonedDateTime time) {
        Batch b = batch();
        Result r = apply(b, deviceId, mappings, reading, time);
        commit(b);
        return r;
    }

    public Result apply(Batch batch, String deviceId, List<InputMapping> mappings, InputReading reading,
            ZonedDateTime time) {
        if (mappings.isEmpty() || reading.isEmpty()) {
            return Result.NONE;
        }
        Map<String, Seen> committed = state.getOrDefault(deviceId, Map.of());
        Map<String, Seen> draft = batch.draft.computeIfAbsent(deviceId, k -> new HashMap<>());
        Map<String, Object> states = new LinkedHashMap<>();
        List<Event> events = new ArrayList<>();
        Instant t = time.toInstant();
        for (InputMapping m : mappings) {
            Boolean on = on(m, reading);
            if (on == null) {
                continue;
            }
            states.put(m.label(), m.analog()
                    ? Map.of("on", on, "volts", reading.analog().get(m.source()))
                    : on);
            Seen previous = draft.containsKey(m.source()) ? draft.get(m.source()) : committed.get(m.source());
            if (previous != null && !t.isAfter(previous.at())) {
                continue;
            }
            draft.put(m.source(), new Seen(on, t));
            boolean changed = previous == null ? m.source().equals(reading.trigger()) : previous.on() != on;
            if (changed && (on ? m.eventOn() : m.eventOff())) {
                events.add(event(on ? m.onEvent() : m.offEvent(), m, time));
            }
        }
        return new Result(states, events);
    }

    /** Keeps the batch's states (the newest per input, when batches of one device overlap). */
    public void commit(Batch batch) {
        batch.draft.forEach((device, seen) -> {
            Map<String, Seen> current = state.computeIfAbsent(device, k -> new ConcurrentHashMap<>());
            seen.forEach((source, s) -> current.merge(source, s, (old, neu) -> neu.at().isAfter(old.at()) ? neu : old));
        });
    }

    /** Forgets devices not in {@code keep} (idle eviction, together with the duplicate filter). */
    public void retainAll(Set<String> keep) {
        state.keySet().retainAll(keep);
    }

    /** Forgets one device's state (its input profile changed). */
    public void forget(String deviceId) {
        state.remove(deviceId);
    }

    private static Boolean on(InputMapping m, InputReading r) {
        if (m.analog()) {
            Double v = r.analog().get(m.source());
            if (v == null) {
                return null;
            }
            boolean above = v >= m.thresholdV();
            return m.activeHigh() == above;
        }
        Boolean level = r.digital().get(m.source());
        return level == null ? null : level == m.activeHigh();
    }

    private static Event event(String type, InputMapping m, ZonedDateTime time) {
        var e = new Event();
        e.setEventType(type);
        e.setTimestamp(time);
        e.setDescription(m.label() + " (" + m.source() + ")");
        return e;
    }

    /** Devices with state, for tests. */
    int size() {
        return state.size();
    }
}
